def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("submission_dir", type=Path)
    ap.add_argument("-n", type=int, default=15, help="number of tasks (stratified by repo)")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--tasks", help="comma-separated instance_ids (overrides -n)")
    ap.add_argument("-o", "--out", type=Path)
    a = ap.parse_args()
    ids = a.tasks.split(",") if a.tasks else pick_tasks(a.n, a.seed)
    out = a.out or ROOT / "notebooks" / f"eval_{a.submission_dir.name}.ipynb"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(build(a.submission_dir, ids), indent=1, ensure_ascii=False))
    print(f"wrote {out} with {len(ids)} tasks: {ids}")


