"""Generate a Kaggle notebook that runs a submission on a small task sample on 4xL4.

The submission files are embedded in the notebook, so what you test is exactly
what you submit. The notebook measures per-task wall time, tool calls, LLM calls
and resolve rate, and projects the full 12 h scorer run.

Usage: python scripts/make_eval_notebook.py submissions/v1 [-n 15] [-o notebooks/eval_v1.ipynb]
"""
