ROOT = Path(__file__).resolve().parent.parent


def pick_tasks(n: int, seed: int) -> list[str]:
    """Stratified sample by repo, deterministic."""
    rows = [json.loads(l) for l in (ROOT / "data" / "tasks.jsonl").read_text().splitlines() if l.strip()]
    by_repo = defaultdict(list)
    for r in rows:
        by_repo[r["repo"]].append(r["instance_id"])
    rng = random.Random(seed)
    out = []
    for repo, ids in sorted(by_repo.items()):
        k = max(1, round(n * len(ids) / len(rows)))
        out += rng.sample(sorted(ids), min(k, len(ids)))
    return sorted(out)


